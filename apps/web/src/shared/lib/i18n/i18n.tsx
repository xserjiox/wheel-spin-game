const defaultOptions: Record<Locale, string[]> = {
  en: ["Pizza", "Sushi", "Burgers", "Pasta", "Salad"],
  ru: ["Пицца", "Суши", "Бургеры", "Паста", "Салат"],
  uk: ["Піца", "Суші", "Бургери", "Паста", "Салат"],
  de: ["Pizza", "Sushi", "Burger", "Pasta", "Salat"],
  zh: ["披萨", "寿司", "汉堡", "意大利面", "沙拉"],
};

export type Translate = (
  key: TranslationKey,
  variables?: Record<string, string | number>,
) => string;

type I18nValue = {
  locale: Locale;
  localeTag: string;
  setLocale: (locale: Locale) => void;
  t: Translate;
  defaultRoomOptions: string[];
};

const I18nContext = createContext<I18nValue | null>(null);
const STORAGE_KEY = "wheel-spin-locale";

function initialLocale(): Locale {
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored && stored in dictionaries) return stored as Locale;
  return "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);
  const t = useCallback<Translate>(
    (key, variables) => {
      let value = dictionaries[locale][key];
      for (const [name, replacement] of Object.entries(variables ?? {})) {
        value = value.replaceAll(`{${name}}`, String(replacement));
      }
      return value;
    },
    [locale],
  );

  const setLocale = useCallback((nextLocale: Locale) => {
    window.localStorage.setItem(STORAGE_KEY, nextLocale);
    setLocaleState(nextLocale);
  }, []);

  useEffect(() => {
    document.documentElement.lang =
      locale === "uk" ? "uk" : locale === "zh" ? "zh-CN" : locale;
    document.title = t("metaTitle");
    document
      .querySelector('meta[name="description"]')
      ?.setAttribute("content", t("metaDescription"));
  }, [locale, t]);

  const value = useMemo<I18nValue>(
    () => ({
      locale,
      localeTag: localeTags[locale],
      setLocale,
      t,
      defaultRoomOptions: defaultOptions[locale],
    }),
    [locale, setLocale, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

// Context hooks intentionally share the provider module.
// eslint-disable-next-line react-refresh/only-export-components
export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

